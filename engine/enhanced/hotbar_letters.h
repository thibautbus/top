/* The letter of `c` (a lower case letter as its capital), or the question mark's. */
static inline const HotbarLetter *hotbar_letter(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    const HotbarLetter *unknown = NULL;
    for (unsigned i = 0; i < sizeof hotbar_letters / sizeof hotbar_letters[0]; i++) {
        if (hotbar_letters[i].c == c) return &hotbar_letters[i];
        if (hotbar_letters[i].c == '?') unknown = &hotbar_letters[i];
    }
    return unknown;
}

